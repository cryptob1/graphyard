import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { withDatabase } from './helpers/postgres.js';
import { Engine } from '../src/engine.js';
import { server } from '../src/server.js';
import type { Principal } from '../src/model.js';

// Real CLI, control plane, Postgres and dashboard; no mocked answer or browser routes.
test('e2e:owner-relayed-answer — owner direction relayed by the master is recorded and reversible', async () => {
  const store = await withDatabase('owner-relayed-answer'); await store.init();
  const owner: Principal = { id: 'owner', role: 'admin', sessionKind: 'human' };
  const master: Principal = { id: 'master', role: 'operator-agent', sessionKind: 'ai', scope: { repositories: ['owner/project'], workItems: ['*'] } };
  const worker: Principal = { id: 'worker', role: 'worker', sessionKind: 'ai' };
  const token = (actor: Principal) => `${actor.id}-${'x'.repeat(32)}`;
  const engine = new Engine(store, 120, 'owner/project'); engine.gitRunner = null;
  const http = server(engine, [owner, master, worker].map(actor => ({ ...actor, token: token(actor) })));
  await new Promise<void>(done => http.listen(0, '127.0.0.1', done));
  const url = `http://127.0.0.1:${(http.address() as { port: number }).port}`;
  const post = async (actor: Principal, path: string, body: unknown) => {
    const response = await fetch(`${url}/api/${path}`, { method: 'POST', headers: { Authorization: `Bearer ${token(actor)}`, 'Content-Type': 'application/json', 'Idempotency-Key': randomUUID() }, body: JSON.stringify(body) });
    const data = await response.json(); assert.equal(response.status, 200, JSON.stringify(data)); return data;
  };
  const read = async (path: string) => (await fetch(`${url}/api/${path}`, { headers: { Authorization: `Bearer ${token(owner)}` } })).json();
  const cli = (...args: string[]) => promisify(execFile)(process.execPath, [resolve('bin/graphyard.mjs'), ...args], { env: { ...process.env, GRAPHYARD_URL: url, GRAPHYARD_TOKEN: token(master), GRAPHYARD_TOKEN_FILE: undefined } });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    let work = await engine.execute(owner, 'create', null, { type: 'chore', title: 'Owner decides timing', criteria: [{ id: 'AC-1', text: 'The printer prints a receipt', proofs: ['human:receipt', 'e2e:fixture'] }] }, randomUUID());
    work = await engine.execute(owner, 'ready', work.id, {}, randomUUID());
    work = await engine.execute(worker, 'claim', work.id, {}, randomUUID());
    await post(worker, `work/${work.id}/park`, { epoch: work.epoch, kind: 'goals-and-priorities', needed: 'Should this goal start now?', reason: 'The owner chooses timing', recommendation: 'Go ahead as asked', why: 'The implementation is ready.' });
    await assert.rejects(cli('answer', work.key, '--decline', 'Wait'), /--owner-said/);
    await cli('answer', work.key, '--owner-said', 'Not yet', '--decline', 'Wait');
    let saved = await read(`work/${work.id}`);
    assert.equal(saved.humanRequest, null);
    assert.equal(saved.humanRequests[0].answer.by, 'master');
    assert.equal(saved.humanRequests[0].answer.ownerSaid, 'Not yet');
    assert.equal(saved.humanRequests[0].answer.outcome, 'declined');
    assert.equal((await read('human-requests')).requests.some((row: any) => row.id === work.id), false);
    await post(owner, `work/${work.id}/human-proof-request`, { proof: 'human:receipt', sha: 'a'.repeat(40), baseSha: 'b'.repeat(40) });
    await assert.rejects(cli('answer', work.key, 'Printed'), /--owner-said/);
    await cli('answer', work.key, '--owner-said', 'It printed cleanly', 'Printed');
    saved = await read(`work/${work.id}`);
    assert.equal(saved.humanProofs[0].answer.ownerSaid, 'It printed cleanly');
    assert.equal(saved.humanProofs[0].answer.by, 'master');
    assert.equal(saved.evidence.at(-1).result, 'pass');
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage();
    await page.goto(`${url}/?sign-in`);
    await page.getByLabel('Access token').fill(token(owner));
    await page.getByRole('button', { name: 'Open control plane' }).click();
    await page.getByRole('button', { name: /Needs you/ }).click();
    await page.getByRole('button', { name: /Every request and answer/ }).click();
    await expect(page.getByText('relayed by master from the owner: "Not yet"', { exact: true })).toBeVisible();
    await expect(page.getByText('relayed by master from the owner: "It printed cleanly"', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Reverse answer', exact: true }).click();
    await expect(page.getByText('Owner reversed the relayed answer', { exact: true })).toBeVisible();
    saved = await read(`work/${work.id}`);
    assert.equal(saved.blocker, null);
    assert.deepEqual(saved.humanRequests.map((entry: any) => [entry.answer.by, entry.answer.outcome]), [['master', 'declined'], ['owner', 'provided']]);
    await page.getByRole('button', { name: 'Reverse check answer', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Reverse check answer', exact: true })).toHaveCount(0);
    saved = await read(`work/${work.id}`);
    assert.equal(saved.humanProofs[0].answer.outcome, 'fail');
    const events = (await store.pool.query("SELECT actor, payload FROM events WHERE work_id=$1 AND kind IN ('human.answered','human-proof.answered') ORDER BY seq", [work.id])).rows;
    assert.deepEqual(events.map(event => event.actor), ['master', 'master', 'owner', 'owner']);
    assert.match(JSON.stringify(events[0].payload), /Not yet/);
    assert.match(JSON.stringify(events[1].payload), /It printed cleanly/);
    await page.getByRole('button', { name: /Owner decides timing/ }).first().click();
    await page.locator('summary').filter({ hasText: /^History/ }).click();
    const history = page.getByRole('region', { name: 'History entries' });
    await expect(history).toContainText('relayed by master from the owner: "Not yet"');
    await expect(history).toContainText('relayed by master from the owner: "It printed cleanly"');
    await expect(history).toContainText('Owner reversed the relayed answer');
  } finally { await browser?.close(); await new Promise<void>(done => http.close(() => done())); await store.close(); }
});
