import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { guideText, guideTopicList } from '../src/guide.js';
import { masterGuide } from '../src/master/guide.js';
import { masterInstructions } from '../src/master/instructions.js';

// GY-3109: procedures agents need live in CLI text; nothing in src/ or web/ points at a removed page.
const root = fileURLToPath(new URL('..', import.meta.url));
// A header older installs generated into workflow files; setup matches it to remove them, it links nothing.
const legacyHeader = '# Generated by graphyard init from the delivery policy in graphyard.json (docs/onboarding.md).';
const files = (dir: string): string[] => readdirSync(join(root, dir), { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(join(dir, entry.name)) : /\.(ts|tsx|mjs|css|html)$/.test(entry.name) ? [join(dir, entry.name)] : []);

test('unit:guides-without-docs — guide TOPIC and master guide print complete procedures naming no docs page, and no src/ or web/ text links to a deleted page', () => {
  for (const topic of guideTopicList) {
    const text = execFileSync(process.execPath, ['bin/graphyard.mjs', 'guide', topic], { cwd: root, encoding: 'utf8' });
    assert.equal(text.trim(), guideText(topic).trim(), `guide ${topic} prints its procedure`);
    assert.doesNotMatch(text, /docs\//, `guide ${topic} names no docs page`);
  }
  const master = execFileSync(process.execPath, ['bin/graphyard.mjs', 'master', 'guide'], { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  assert.equal(master, `${masterInstructions}\n${masterGuide}\n`);
  for (const section of ['## The loop', '## Automatic dispatch at submit', 'master status', 'e2e:NAME']) assert.ok(master.includes(section), `master guide carries ${section}`);
  assert.doesNotMatch(master, /docs\/|\]\([^)]*\.md\)/, 'master guide names no docs page');

  for (const file of [...files('src'), ...files('web')]) {
    const text = readFileSync(join(root, file), 'utf8').replace(legacyHeader, '');
    for (const [reference] of text.matchAll(/\bdocs\/[\w./-]*\w/g)) assert.ok(existsSync(join(root, reference)), `${file} names ${reference}, which does not exist`);
    assert.doesNotMatch(text, /["'`]\/docs\b/, `${file} links the removed /docs pages`);
  }
});
